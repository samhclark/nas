def service_toml(
    *,
    name: str = "service",
    uid: int = 51999,
    subid_start: int = 519990000,
    application: str | None = None,
    role: str = "test",
    container: str = "",
    krun: str | None = None,
    probe_endpoint: str | None = None,
    extra: str = "",
) -> str:
    if krun is None:
        if probe_endpoint is None:
            probe_endpoint = "probe"
            container += '\n[[container.endpoints]]\nname = "probe"\nport = 65535\n'
